def get_colors(dark):
    """Get CSS string with Anki colors"""
    css = ":root {\n"
    for key, val in colors.__dict__.items():
        if type(val) is dict and (val_ := val.get('dark') if dark else val.get('light')):
            css += f'''   --{key.lower().replace('_', '-')}: {val_};\n'''
    css += '}'
    return css

