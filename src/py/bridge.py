def clean_text(text: str):
    """
    Clean text to "markdown style"
    """
    def parse_roman(roman: str):
        """Parse roman numerals to int"""
        romans = {'I': 1, 'V': 5, 'X': 10, 'L': 50, 'C': 100, 'D': 500, 'M': 1000}
        tot = 0
        prev = 0
        for c in reversed(roman):
            val = romans[c.upper()]
            if val < prev:
                tot -= val
            else:
                tot += val
            prev = val
        
        return tot

    def repl_list(m: re.Match):
        if g := m.group('number'):
            return f'{m.group("space")}{g}. '
        elif g := m.group('letter'):
            i = 0
            for c in g:
                i += ord(c.lower()) - 96
            return f'{m.group("space")}{i}. '
        elif g := m.group('roman'):
            return f'{m.group("space")}{parse_roman(g)}. '
        elif g := m.group('bullet'):
            return f'{m.group("space")}- '

        # Shouldn't happen
        return m.group(0)

    # Check for lists - number, letter, roman, non-letter
    text = re.sub(
        r'''^
          (?P<space>\s*)
          (?:
            (?P<number>[0-9]{1,2})[.),:;]? |
            (?P<letter>[a-zA-z])[.),:;] |
            (?P<roman>
                (?:M{0,3})?
                (?:CM|CD|D?C{0,3})?
                (?:XC|XL|L?X{0,3})?
                (?:IX|IV|V?I{0,3})
                [.),:;]
            ) |
            (?P<bullet>[^a-zA-Z#\u00C0-\u00FF\u0100-\u017F\u0180-\u024F\u1E00-\u1EFF\u0400-\u04FF\u0500-\u052F\u0530-\u058F\d])
          )
          (?:\s+\n?)                # Following space(s) and possibly 1 newline
          (?![\s\n])                # Not followed by additional space/newline
        ''',
        repl_list,
        text,
        flags=re.VERBOSE + re.MULTILINE
    )
    
    return text
