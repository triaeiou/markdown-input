im_utils = -1

def get_addon(addon: list[str]):
    """
    Get other addon module if installed
    """
    for _id in mw.addonManager.allAddons():
        meta = mw.addonManager.addon_meta(_id)
        if meta.enabled and _id in addon and strvercmp(meta.human_version, '1.1.0') >= 0:
            try:
                return importlib.import_module(_id)
            except ModuleNotFoundError:
                pass
    return None

def handler(msg: str, window: QMainWindow, webview: QWebEngineView) -> str:
    """
    Handle bridge messages
    """
    global im_utils
    if im_utils == -1:
        if imu := sys.modules.get('inline-media.utils') or sys.modules.get('683715045.utils'):
            im_utils = imu
        else:
            im_utils = None
    res = None

    mime = QApplication.clipboard().mimeData(QClipboard.Mode.Clipboard)
    if msg.startswith('clipboard-contents'):
        res = {
            'image': mime.hasImage(),
            'text': mime.hasText(),
            'html': mime.hasHtml(),
            'media': bool(im_utils.parse_clipboard()) if im_utils else False
        }
    elif msg.startswith('clipboard-html'):
        res = clean_html(mime.html())
    elif msg.startswith('clipboard-text'):
        res = clean_text(mime.text())
    elif msg.startswith('clipboard-raw'):
        res = mime.text()
    elif msg.startswith('clipboard-image'):
        res = ''
        if mime.hasImage():
            im = QImage(mime.imageData())
            uname = namedtmp(datetime.datetime.now().strftime('paste-%y.%m.%d-%H.%M.%S'))
            if mw.col.get_config_bool(Config.Bool.PASTE_IMAGES_AS_PNG):
                ext = ".png"
                im.save(uname + ext, None, 50)
            else:
                ext = ".jpg"
                im.save(uname + ext, None, 80)

            path = uname + ext
            if os.path.exists(path):
                res = f"![]({mw.col.media.add_file(path)})"
    elif msg.startswith('clipboard-media') or msg.startswith('clipboard-audio'):
        # Add media to media library and create inline media tag
        # A little more involved as we want to do the conversion in background thread
        res = ''
        if im_utils:
            if srcs := im_utils.parse_clipboard():
                t = 'video' if msg.startswith('clipboard-media') else 'audio'
                cb = msg[msg.index(':') + 1:].strip()
                # Background thread func for adding the media
                def background(*_):
                    media = im_utils.add_media(srcs[:1], t)
                    return im_utils.tag_media(media[0])
                def success(html: str):
                    webview.page().runJavaScript(f'''(function () {{
                        {cb}({json.dumps(html)});
                    }})();'''
                )
                operations.QueryOp(parent=window, op=background, success=success).with_progress('Downloading and converting media...').run_in_background()
    return res

def clean_html(html: str) -> str:
    """
    Clean HTML, including HTML generated by Word.
    """
    # Normalize line endings
    html = html.replace('\r\n', '\n').replace('\r', '\n')
    # Strip to fragment
    html = re.sub(r'.*?<!--StartFragment-->\s*(.*?)\s*<!--EndFragment-->.*', r'\1', html, flags=re.DOTALL)
    # Remove Word compat statements
    html = re.sub(r'<!(?:[^-].*?>|>)', r'', html)

    soup = BeautifulSoup(html, 'html.parser')
    if soup.body:
        soup.contents = soup.body.contents
    
    # Convert/fix Word specific tags
    # Titles and headings
    if t := soup.select('p.MsoTitle'):
        # Increase headings to make h1 == title
        for h in soup.select('h1, h2, h3, h4, h5, h6'):
            # Remove Word auto link
            for l in h.select('a[name^="OLE_LINK"]'):
                l.unwrap()
            n = int(h.name[1:])
            n = n + 1 if n < 5 else 6
            h.name = f'h{n}'
        # Title to h1
        for t in soup.select('p.MsoTitle'):
            t.name = 'h1'

    # Lists
    for l in soup.select('p.MsoListParagraph'):
        l.name = 'li'
        l.wrap(soup.new_tag('xl'))
    
    for ls in soup.select('p.MsoListParagraphCxSpFirst'):
        xl = soup.new_tag('xl')
        ls.insert_before(xl)
        nxt = ls
        while cur := nxt:
            nxt = nxt.next_sibling
            if isinstance(cur, Tag):
                cur.name = 'li'
                xl.append(cur)
                if 'MsoListParagraphCxSpLast' in cur['class']:
                    break

    # Determine list types
    for xl in soup.select('xl'):
        xlname = None
        # Remove all bullets and set list type depending on first child
        for m in xl.select('span[style*="mso-list:Ignore"]'):
            if not xlname:
                xlname = 'ol' if m.text.strip()[0].isalnum() else 'ul'
            m.decompose()
        xl.name = xlname or 'ul'
    
    # Remove Word-specific tags
    for tag in soup(['meta', 'style', 'script', 'link', 'o:p']):
        tag.decompose()
    
    # Remove conditional comments
    clean = re.sub(r'<!--\[if[^\]]*?\]>(.*?)<!\[endif\]-->', r'\1', str(soup))
    # Keep fragment only
    clean = re.sub(r'.*?<!--StartFragment-->(?:\s|\\n)*(.*?)(?:\s|\\n)*<!--EndFragment-->', r'\1', clean)
    
    return clean
 
